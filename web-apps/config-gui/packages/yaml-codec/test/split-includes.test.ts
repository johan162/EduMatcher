/** Split output: symbols and participants in included files (pm-config-gen --split). */

import { describe, expect, it } from "vitest";
import yaml from "js-yaml";
import {
  createApiGateway,
  createBlankDraft,
  createGateway,
  deriveIpoQuote,
  type EngineConfigDraft,
} from "@edumatcher/schema";
import { generateFiles, generateYaml, parseConfigFiles } from "../src/index.js";

const DATE = { generatedDate: "2026-11-07" };

function exchange(): EngineConfigDraft {
  const draft = createBlankDraft();
  draft.gateways = [createGateway("T1"), createGateway("MM1", "MARKET_MAKER")];
  draft.symbolOrder = ["AAPL", "MSFT"];
  draft.symbols = {
    AAPL: {
      tickDecimals: 2,
      lastBuyPrice: 100,
      lastSellPrice: 100,
      marketMakerQuotes: [deriveIpoQuote("MM1", 100, 2)],
    },
    MSFT: { tickDecimals: 2, lastBuyPrice: 200, lastSellPrice: 200 },
  };
  return draft;
}

/** Merge as the engine's loader does for these keys: the included files supply them. */
function merged(files: Array<{ text: string }>): Record<string, unknown> {
  const [main, ...parts] = files.map((f) => yaml.load(f.text) as Record<string, unknown>);
  const { include: _include, ...rest } = main!;
  return Object.assign(rest, ...parts);
}

describe("generateFiles", () => {
  it("writes one file, identical to generateYaml, when not split", () => {
    const draft = exchange();
    expect(generateFiles(draft, DATE)).toEqual([
      { name: "engine_config.yaml", text: generateYaml(draft, DATE) },
    ]);
  });

  it("moves symbols and participants to included files that merge back to the same config", () => {
    const draft = exchange();
    draft.output.splitIncludes = true;
    draft.output.filename = "exchange.yaml";
    const files = generateFiles(draft, DATE);
    expect(files.map((f) => f.name)).toEqual(["exchange.yaml", "symbols.yaml", "participants.yaml"]);

    const main = yaml.load(files[0]!.text) as Record<string, unknown>;
    expect(main.include).toEqual(["symbols.yaml", "participants.yaml"]);
    expect(main).not.toHaveProperty("symbols");
    expect(main).not.toHaveProperty("participants");
    expect(Object.keys(yaml.load(files[1]!.text) as object)).toEqual(["symbols"]);
    expect(Object.keys(yaml.load(files[2]!.text) as object)).toEqual(["participants"]);

    expect(merged(files)).toEqual(yaml.load(generateYaml(draft, DATE)));
  });

  it("renders the include list and included files as pm-config-gen does", () => {
    const draft = exchange();
    draft.output.splitIncludes = true;
    const [main, symbols] = generateFiles(draft, DATE);
    expect(main!.text).toContain("# -- Included files --\ninclude:\n- symbols.yaml\n- participants.yaml\n");
    expect(symbols!.text.startsWith(
      "# Generated by pm-config-gen v1.0.0-gui on 2026-11-07\n" +
        "# Included from engine_config.yaml through its 'include:' list.\n\n" +
        "# -- Symbol universe --\n# symbol universe\nsymbols:\n",
    )).toBe(true);
  });
});

describe("parseConfigFiles", () => {
  it("round-trips a split export exactly and keeps split output on", () => {
    const draft = exchange();
    draft.output.splitIncludes = true;
    const files = generateFiles(draft, DATE);
    // The browser hands the files over in any order.
    const { draft: imported, notes } = parseConfigFiles([files[2]!, files[0]!, files[1]!]);
    expect(notes).toEqual([]);
    expect(imported.output.splitIncludes).toBe(true);
    expect(generateFiles(imported, DATE)).toEqual(files);
  });

  it("imports a single file as before, with split output off", () => {
    const draft = exchange();
    const { draft: imported, notes } = parseConfigFiles([{ name: "x.yaml", text: generateYaml(draft, DATE) }]);
    expect(notes).toEqual([]);
    expect(imported.output.splitIncludes).toBe(false);
    expect(generateYaml(imported, DATE)).toBe(generateYaml(draft, DATE));
  });

  it("merges as the engine does and notes a layout the export cannot reproduce", () => {
    const main = "include:\n- conf/more.yaml\nparticipants:\n- id: T1\n  role: TRADER\n";
    const more = "participants:\n- id: T2\n  role: TRADER\nsymbols:\n  AAPL:\n    tick_decimals: 2\n";
    const { draft, notes } = parseConfigFiles([
      { name: "main.yaml", text: main },
      { name: "more.yaml", text: more },
    ]);
    expect(draft.gateways.map((g) => g.id)).toEqual(["T1", "T2"]);
    expect(draft.symbolOrder).toEqual(["AAPL"]);
    expect(draft.output.splitIncludes).toBe(true);
    expect(notes).toHaveLength(1);
    expect(notes[0]).toMatch(/laid out differently/);
  });

  it("refuses what the engine refuses, and selections it cannot resolve", () => {
    const main = (list: string) => ({ name: "main.yaml", text: `include: ${list}\n` });
    const f = (name: string, text: string) => ({ name, text });
    const api = (body: string) => ({ name: "main.yaml", text: `api_gateways:\n  default:\n    ${body}\n` });
    const cases: Array<[Array<{ name: string; text: string }>, RegExp]> = [
      [[main("[symbols.yaml]")], /names the include 'symbols\.yaml'\. Import again and select it/],
      [[main("[../x.yaml]")], /relative path without '\.\.'/],
      [[main("[/etc/x.yaml]")], /relative path without '\.\.'/],
      [[main("[a/s.yaml, b/s.yaml]"), f("s.yaml", "")], /a\/s\.yaml and b\/s\.yaml are both named s\.yaml/],
      [[main("[s.yaml]"), f("s.yaml", "include: []\n")], /Only one selected file/],
      [[main("[s.yaml]"), f("s.yaml", ""), f("p.yaml", "")], /does not name p\.yaml/],
      [[f("a.yaml", "x: 1\n"), f("b.yaml", "y: 1\n")], /none has an 'include:' list/],
      [[main("symbols.yaml")], /'include' must be a list/],
      [[{ name: "main.yaml", text: "include: [s.yaml]\nsessions_enabled: true\n" }, f("s.yaml", "sessions_enabled: false\n")], /'sessions_enabled' is already defined in main\.yaml/],
      [[{ name: "main.yaml", text: "include: [s.yaml]\nsymbols:\n  A: {}\n" }, f("s.yaml", "symbols:\n  A: {}\n")], /'symbols\.A' is already defined/],
      [[main("[s.yaml]"), f("s.yaml", "- 1\n")], /s\.yaml: must be a YAML mapping/],
      [[main("[s.yaml, ./s.yaml]"), f("s.yaml", "")], /include '\.\/s\.yaml' is listed twice/],
      [[main("[market_sim.yaml]"), f("market_sim.yaml", "")], /'market_sim\.yaml' is a reserved name/],
      [[main("[./engine_config.json]"), f("engine_config.json", "")], /'engine_config\.json' is a reserved name/],
      [[api("credentials_file: keys.yaml")], /names the credentials file 'keys\.yaml'\. Import again/],
      [[api("credentials_file: keys.yaml\n    credentials: []"), f("keys.yaml", "")], /has both 'credentials' and 'credentials_file'/],
      [[api("credentials_file: 3"), f("keys.yaml", "")], /api_gateways\.default\.credentials_file must be a name/],
      [[api("credentials_file: ../keys.yaml"), f("keys.yaml", "")], /relative path without '\.\.'/],
      [[api("credentials_file: engine_config.yaml"), f("engine_config.yaml", "")], /'engine_config\.yaml' is a reserved name/],
      [[api("credentials_file: keys.yaml"), f("keys.yaml", "oops\n")], /keys\.yaml: must be a YAML list of credentials/],
    ];
    for (const [files, message] of cases) expect(() => parseConfigFiles(files)).toThrow(message);
  });

  it("reads a credentials file relative to the file defining the gateway, and writes it back", () => {
    const main = "include:\n- conf/api.yaml\nparticipants:\n- id: T1\n  role: TRADER\n";
    const apiFile = "api_gateways:\n  default:\n    port: 8080\n    credentials_file: keys.yaml\n";
    const keys = "- api_key: abc\n  gateway_id: T1\n  description: desk\n";
    // The path is conf/keys.yaml, so a top-level reserved name check does not apply to it.
    const { draft } = parseConfigFiles([
      { name: "main.yaml", text: main },
      { name: "api.yaml", text: apiFile },
      { name: "keys.yaml", text: keys },
    ]);
    expect(draft.apiGateways[0]!.credentialsFile).toBe("keys.yaml");
    expect(draft.apiGateways[0]!.credentials).toEqual([{ apiKey: "abc", gatewayId: "T1", description: "desk" }]);
  });

  it("round-trips a credentials file exactly, without the main file holding the keys", () => {
    const draft = exchange();
    draft.apiGateways = [{ ...createApiGateway("default"), credentialsFile: "api_keys.yaml" }];
    draft.apiGateways[0]!.credentials = [{ apiKey: "k1", gatewayId: "T1", description: "" }];
    for (const split of [false, true]) {
      draft.output.splitIncludes = split;
      const files = generateFiles(draft, DATE);
      expect(files.map((f) => f.name)).toContain("api_keys.yaml");
      expect(files[0]!.text).not.toContain("k1");
      const { draft: imported, notes } = parseConfigFiles([...files].reverse());
      expect(notes).toEqual([]);
      expect(generateFiles(imported, DATE)).toEqual(files);
    }
  });

  it("writes a credentials file shared by several gateways once", () => {
    const draft = exchange();
    const creds = [{ apiKey: "k1", gatewayId: null, description: "" }];
    draft.apiGateways = [
      { ...createApiGateway("a"), credentials: creds, credentialsFile: "keys.yaml" },
      { ...createApiGateway("b"), port: 8081, credentials: creds, credentialsFile: "keys.yaml" },
    ];
    const files = generateFiles(draft, DATE);
    expect(files.map((f) => f.name)).toEqual(["engine_config.yaml", "keys.yaml"]);
    expect(generateFiles(parseConfigFiles(files).draft, DATE)).toEqual(files);
  });
});
