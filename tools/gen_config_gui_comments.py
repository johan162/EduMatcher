#!/usr/bin/env python3
"""Regenerate config-gui's copy of the --comment-default-config-fields text.

web-apps/config-gui writes engine_config.yaml in the browser, so it needs the
commented defaults header as TypeScript. This writes
``packages/yaml-codec/src/defaultFieldComments.ts`` from
``build_default_engine_field_comment_lines`` -- the one source -- and
tests/test_config_gui_mirrors.py fails until it is rerun after a change.

Usage::

    poetry run python tools/gen_config_gui_comments.py
"""

from __future__ import annotations

import json
from pathlib import Path

from edumatcher.config_gen.cli_comments import build_default_engine_field_comment_lines

TARGET = (
    Path(__file__).resolve().parents[1]
    / "web-apps/config-gui/packages/yaml-codec/src/defaultFieldComments.ts"
)

HEADER = """\
/**
 * Static comment block emitted when `--comment-default-config-fields` is on.
 *
 * GENERATED by tools/gen_config_gui_comments.py from
 * `build_default_engine_field_comment_lines` in
 * src/edumatcher/config_gen/cli_comments.py (whose output does not depend on
 * the config). Do not edit by hand: rerun the generator after changing the
 * Python text. tests/test_config_gui_mirrors.py fails while the two differ.
 */

export function buildDefaultEngineFieldCommentLines(): string[] {
  return [
"""

FOOTER = """\
  ];
}
"""


def render() -> str:
    """The TypeScript module text for the current Python comment lines."""
    lines = build_default_engine_field_comment_lines({})
    # JSON string literals are valid TypeScript string literals.
    body = "".join(f"    {json.dumps(line, ensure_ascii=False)},\n" for line in lines)
    return HEADER + body + FOOTER


def main() -> None:
    TARGET.write_text(render(), encoding="utf-8")
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
